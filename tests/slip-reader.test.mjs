import assert from 'node:assert/strict';
import {parseSlipText,dateRegions} from '../slip-reader.js';
assert.deepEqual(parseSlipText('จำนวนเงิน 1,234.50 บาท\n12 ต.ค. 2569'),{amount:'1234.50',date:'2026-10-12'});
assert.deepEqual(parseSlipText('Amount 99.00 THB\n12 Oct 2026\nFee 0.00'),{amount:'99.00',date:'2026-10-12'});
assert.deepEqual(parseSlipText('๙๙.๕๐ บาท\n๑๒/๑๐/๒๕๖๙'),{amount:'99.50',date:'2026-10-12'});
assert.equal(parseSlipText('99.00\n199.00\n31/02/2026').amount,'');
assert.equal(parseSlipText('99.00\n199.00\n31/02/2026').date,'');
assert.deepEqual(parseSlipText('บัญชี 1234567890\n12/10/2026'),{amount:'',date:'2026-10-12'});
assert.equal(parseSlipText('12/10/2026\n13/10/2026').date,'');
console.log('PASS slip parser: Thai/English dates, Buddhist years, Thai digits, fees, ambiguity and invalid dates');
for(const text of ['12ต.ค.2569 17:13','12 ต.ค.2569','12 ต. ค. 2569','12 ต ค 2569','12ตุลาคม2569','12Oct2026'])assert.equal(parseSlipText(text).date,'2026-10-12',text);
console.log('PASS OCR date whitespace, joined tokens and full Thai months');
for(const text of ['12 ต.ค. 69','12 ตุลาคม พ.ศ. 2569','12 October 2026','12 OCT 26','12/10/69','12.10.2569','2026-10-12','2026/10/12','12 / 10 / 2026'])assert.equal(parseSlipText(text).date,'2026-10-12',text);
for(const text of ['จำนวน\n100.00 บาท\nค่าธรรมเนียม 10.00','Amount\nTHB 1,200.50\nFee 25.00','ยอดโอน 100 บาท','THB 100','฿100'])assert.notEqual(parseSlipText(text).amount,'',text);
assert.equal(parseSlipText('จำนวนเงิน 100.00 บาท\nค่าธรรมเนียม 10.00').amount,'100.00');
assert.equal(parseSlipText('Amount\nTHB 1,200.50\nFee 25.00').amount,'1200.50');
assert.equal(parseSlipText('ยอดโอน 100 บาท').amount,'100.00');
assert.equal(parseSlipText('เลขที่รายการ 1234567890\nวันที่ 12.10.2026 เวลา 17:13').amount,'');
assert.equal(parseSlipText('12 ต.ค. 2569\n13 ต.ค. 2569').date,'');
console.log('PASS general bank text formats: short Buddhist years, ISO dates, numeric dates, full English months, integer currency and nonzero fee exclusion');
for(const text of ['จำนวนเงิน\n100.00\nค่าธรรมเนียม\n10.00 บาท','Amount 100.00\nFee\n\n25.00 THB','ยอดเงิน 100.00\nยอดคงเหลือ\n999.00 บาท'])assert.equal(parseSlipText(text).amount,'100.00',text);
for(const text of ['12 ต.ค. ค.ศ. 26','12 ต.ค. ค. ศ. 2026','12 Oct BE 69','12 October AD 2026','12 ต.ค.\n2569','12\nตุลาคม\n2569','12/10/\n2569'])assert.equal(parseSlipText(text).date,'2026-10-12',text);
assert.equal(parseSlipText('12 Oct AD 69').date,'2069-10-12');
assert.equal(parseSlipText('12 Oct AD 2569').date,'');
assert.equal(parseSlipText('Fee\n25.00 THB').amount,'');
assert.equal(parseSlipText('12 ต.ค.\n2569\n13 ต.ค.\n2569').date,'');
console.log('PASS split fee values, explicit eras override month language, multiline dates and contradictory-date guards');
const word=(text,x0,x1)=>({text,bbox:{x0,y0:130,x1,y1:155}});
const regionInput={blocks:[{paragraphs:[{lines:[{words:[word('an',40,120),word('2569',140,210),word('17:13',220,300),word('KBank',600,850)]}]}]}]};
assert.deepEqual(dateRegions(regionInput),[{x0:40,y0:130,x1:300,y1:155}]);
assert.deepEqual(dateRegions({blocks:[]}),[]);
assert.equal(parseSlipText('100.00 บาท\n12 ต.ค. 2569 17:13').date,'2026-10-12');
console.log('PASS date-region detection: year anchor, time boundary and bank logo exclusion');
for(const text of ['12 ๓ต.ค. 2569 17:.15','12 ๓ต.อค. 2569 17:.15','12 ๓ต.ุค. 2569','12 3ต.ค. 2569'])assert.equal(parseSlipText(text).date,'2026-10-12',text);
assert.equal(parseSlipText('03 n.9. 2569 15:36').date,'');
assert.equal(parseSlipText('12 มี.ค. 2569').date,'2026-03-12');
