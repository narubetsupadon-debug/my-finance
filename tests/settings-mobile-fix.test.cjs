const fs=require('node:fs'),assert=require('node:assert/strict'),path=require('node:path');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const css=read('settings-mobile-fix.css'),html=read('index.html'),sw=read('sw.js');
const settingsUrl=html.match(/\.\/settings-mobile-fix\.css\?[^"\s]+/)[0];
assert(sw.includes(settingsUrl),'installed app must cache the exact current Settings CSS URL');
assert.match(css, /\.settings-grid>\.settings-card\[hidden\]/,'collapsed cards override visible-card rules');
assert.match(css, /height:auto!important/);
assert.match(css, /height:46px!important/,'account selector has a bounded height');
assert.match(css, /flex:none!important/,'vertical controls must not inherit a growing flex basis');
assert.match(css, /white-space:nowrap!important/,'status badges cannot wrap one letter at a time');
for(const id of ['healthCheckedAt','settingsLogout','defaultAccountSetting','pushStatusBadge'])assert.equal((html.match(new RegExp('id="'+id+'"','g'))||[]).length,1,id+' preserved');
assert.equal((css.match(/\{/g)||[]).length,(css.match(/\}/g)||[]).length);
console.log('PASS settings layout: collapse cascade, bounded account selector, badge width, exact offline URL and preserved controls');
