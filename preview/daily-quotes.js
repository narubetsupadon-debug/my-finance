const firstDay=Date.UTC(2026,9,17)/86400000;
// 137 is coprime to 366: every quote appears once before the 366-day cycle repeats.
export function dailyQuote(date=new Date()){
 const dayKey=new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Bangkok',year:'numeric',month:'2-digit',day:'2-digit'}).format(date);
 const [year,month,day]=dayKey.split('-').map(Number);
 const elapsed=Date.UTC(year,month-1,day)/86400000-firstDay;
 const index=((elapsed*137)%dailyQuotes.length+dailyQuotes.length)%dailyQuotes.length;
 return {day:dayKey,text:dailyQuotes[index]};
}
